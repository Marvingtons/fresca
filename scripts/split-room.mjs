// Splits the room line drawing (assets/source/fresca-room-lines.svg) into the
// build stages used by the Approach "Plan" panel, and writes
// content/room-lines.ts. Keeps only `.ln` elements; drops <style>, any fills
// (the pigment layer) and any background rect. Every kept element gets
// pathLength="1" so it can draw on with a 1-unit dash.
//
// Run: node scripts/split-room.mjs [path/to/source.svg]
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2] ?? "assets/source/fresca-room-lines.svg";
const svg = readFileSync(src, "utf8");

/** Build order. Top-level <g id> → stage. Anything unlisted is furniture. */
const STAGES = ["floor", "ceiling", "window", "furniture", "olive"];
const STAGE_OF = { floor: "floor", ceiling: "ceiling", window: "window", planter: "olive", "olive-trunk": "olive", "olive-canopy": "olive" };
/** Source strokes are drawn for a large render; scale them up for a ~400px panel,
 *  capping the heavy window frame so it doesn't dominate. */
const STROKE_SCALE = 2.4;
const STROKE_MAX = 1.5;

const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<style[\s\S]*?<\/style>/g, "");

// Walk the top-level groups.
const groups = [];
let depth = 0, start = 0, id = "";
for (const m of body.matchAll(/<(\/?)g\b([^>]*)>/g)) {
  if (m[1]) {
    if (--depth === 0) groups.push({ id, markup: body.slice(start, m.index + m[0].length) });
  } else {
    if (depth++ === 0) { start = m.index; id = m[2].match(/id="([^"]+)"/)?.[1] ?? ""; }
  }
}

const SHAPE = /<(path|line|polyline|polygon|rect|circle|ellipse)\b([^>]*?)\/?>/g;
let kept = 0, dropped = 0;
const clean = (markup) =>
  markup
    .replace(SHAPE, (el, tag, attrs) => {
      const isLine = /class="ln"/.test(attrs) && !/\bfill="(?!none)/.test(attrs);
      const isBackground = tag === "rect" && /width="285"/.test(attrs);
      if (!isLine || isBackground) { dropped++; return ""; }
      kept++;
      const a = attrs
        .replace(/\s*class="ln"/, "")
        .replace(/stroke-width="([^"]+)"/, (_, w) => `stroke-width="${+Math.min(parseFloat(w) * STROKE_SCALE, STROKE_MAX).toFixed(3)}"`)
        .trim();
      return `<${tag} ${a} pathLength="1"/>`;
    })
    .replace(/\s*\n\s*/g, "")
    .replace(/\s+id="[^"]*"/g, "");

const stages = STAGES.map((name) => ({
  name,
  markup: groups.filter((g) => (STAGE_OF[g.id] ?? "furniture") === name).map((g) => clean(g.markup)).join(""),
}));

writeFileSync(
  "content/room-lines.ts",
  `// Generated by scripts/split-room.mjs from ${src}. Do not edit by hand.
// Line layer of the room drawing, split into build stages (draw order).

export const roomViewBox = "${viewBox}";

export const roomStages: { name: string; markup: string }[] = ${JSON.stringify(stages, null, 2)};
`,
);
console.log(`kept ${kept} line elements, dropped ${dropped}`);
for (const s of stages) console.log(`  ${s.name}: ${(s.markup.match(/pathLength/g) ?? []).length}`);

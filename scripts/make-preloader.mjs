// Indexes the preloader stills in public/preloader/ (filename order) and writes
// content/preloader.ts with each image's size, so the first flash can be server
// rendered at the right aspect ratio. The LAST image must be the hero film's
// first frame: it expands into the hero poster.
//
//   node scripts/make-preloader.mjs              index whatever is in the folder
//   node scripts/make-preloader.mjs --standins   first write stand-ins: six kept
//                                                photos + the film's poster as 07
import { readdirSync, writeFileSync, copyFileSync, statSync, rmSync } from "node:fs";
import sharp from "sharp";

const DIR = "public/preloader";

if (process.argv.includes("--standins")) {
  // STAND-INS until the real stills arrive. Mixed ratios on purpose.
  for (const f of readdirSync(DIR)) rmSync(`${DIR}/${f}`);
  // [photo, crop ratio w/h or null for its own]
  const picks = [["black-hood-kitchen-island", null], ["blush-guest-bedroom", null], ["orb-chandelier-dining", 1], ["navy-double-vanity", null], ["cognac-living-room", null], ["walnut-guest-bath", 0.8]];
  for (const [i, [name, ratio]] of picks.entries()) {
    const img = sharp(`public/images/${name}.jpg`);
    const m = await img.metadata();
    const r = ratio ?? m.width / m.height; // one resize: sharp applies only the last
    const [w, h] = r >= 1 ? [560, Math.round(560 / r)] : [Math.round(560 * r), 560];
    await img.resize(w, h, { fit: "cover" }).webp({ quality: 70 }).toFile(`${DIR}/${String(i + 1).padStart(2, "0")}.webp`);
  }
  const poster = process.argv[process.argv.indexOf("--standins") + 1];
  if (!poster || poster.startsWith("--")) throw new Error("--standins needs the path to the film's poster webp as the next argument");
  copyFileSync(poster, `${DIR}/07.webp`); // byte-identical to the hero poster, so the handoff is pixel-exact
}

const files = readdirSync(DIR).filter((f) => /\.(webp|jpe?g|png|avif)$/i.test(f)).sort();
const items = [];
let bytes = 0;
for (const f of files) {
  const m = await sharp(`${DIR}/${f}`).metadata();
  bytes += statSync(`${DIR}/${f}`).size;
  items.push({ src: `/preloader/${f}`, w: m.width, h: m.height });
}
writeFileSync(
  "content/preloader.ts",
  `// Generated by scripts/make-preloader.mjs. Do not edit by hand.
// Preloader stills in play order; the last one is the hero film's first frame.

export const preloaderStills: { src: string; w: number; h: number }[] = ${JSON.stringify(items, null, 2)};
`,
);
console.log(`${items.length} stills, ${(bytes / 1024).toFixed(0)} KB:`, items.map((i) => `${i.src.split("/").pop()} ${i.w}×${i.h}`).join(", "));
